from __future__ import annotations

import locale
from pathlib import Path

LANGUAGES: list[tuple[str, str]] = [
    ("en", "🇺🇸 English"),
    ("es", "🇪🇸 Español"),
    ("fr", "🇫🇷 Français"),
    ("it", "🇮🇹 Italiano"),
    ("de", "🇩🇪 Deutsch"),
    ("zh", "🇨🇳 简体中文"),
    ("ja", "🇯🇵 日本語"),
]

_LANG_CODES = {code for code, _ in LANGUAGES}
_CONFIG_PATH = Path.home() / ".hydra_umc_os_rebuilder_lang.json"


def resolve_initial_lang() -> str:
    saved = _load_saved_lang()
    if saved:
        return saved
    try:
        detected, _encoding = locale.getlocale()
    except (ValueError, TypeError):
        detected = None
    if detected:
        short = detected[:2].lower()
        if short in _LANG_CODES:
            return short
    return "en"


def _load_saved_lang() -> str | None:
    import json

    try:
        data = json.loads(_CONFIG_PATH.read_text(encoding="utf-8"))
        lang = data.get("lang")
        return lang if lang in _LANG_CODES else None
    except (OSError, ValueError):
        return None


def save_lang(code: str) -> None:
    import json

    if code not in _LANG_CODES:
        return
    try:
        _CONFIG_PATH.write_text(json.dumps({"lang": code}), encoding="utf-8")
    except OSError:
        pass


